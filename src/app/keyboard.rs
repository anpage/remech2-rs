/// The `wParam` and `lParam` of a key message.
pub fn params(code: KeyCode, character: Option<char>) -> Option<(usize, isize)> {
    let &(_, virtual_key, scan_code, extended) = KEYS.iter().find(|key| key.0 == code)?;
    let character = character.filter(char::is_ascii).map_or(0, |c| c as u8);

    let virtual_key = if character.is_ascii_alphanumeric() && scan_code < 0x47 {
        character.to_ascii_uppercase()
    } else {
        virtual_key
    };

    let lparam =
        isize::from(character) | isize::from(scan_code) << 16 | isize::from(extended) << 24;
    Some((virtual_key.into(), lparam))
}
