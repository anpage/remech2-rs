// Fills g_soundInfo from the sound table.
// Stack-slot permutation: i and entry.
// FUNCTION: MW2 0x10013370
void InitSoundInfo(void)
{
	MechU32 i;
	SoundTableEntry* entry;
	MechS32 id;

	memset(g_soundInfo, 0xff, sizeof(g_soundInfo));
	for (i = 0, entry = g_soundTable; i < 0x8c; i++, entry++) {
		id = entry->m_id;
		if (id < 1 || id >= 1200) {
			continue;
		}

		g_soundInfo[id].m_priority = entry->m_priority;
		g_soundInfo[id].m_maxCount = entry->m_maxCount;
		g_soundInfo[id].m_rate = entry->m_rate;
		g_soundInfo[id].m_count = 0;
	}
}
